import { chromium } from "playwright-core";
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const pg = await ctx.newPage();
const errors = [];
pg.on("console", (m) => m.type() === "error" && errors.push(m.text()));
pg.on("pageerror", (e) => errors.push(String(e)));
const B = "http://localhost:3100";
const t0 = Date.now();
await pg.goto(B + "/");
await pg.waitForURL("**/boas-vindas");
await pg.getByRole("button", { name: "Começar" }).click();
await pg.getByRole("button", { name: "Continuar" }).click();
await pg.selectOption("#mun", "Cascavel");
await pg.getByRole("button", { name: "Entrar no Talhão" }).click();
await pg.waitForURL(B + "/");
await pg.getByText("O que está acontecendo").waitFor();
console.log("home ok; alertas:", await pg.locator('a[href^="/alertas#"]').count());
await pg.getByRole("link", { name: "Diagnosticar com foto" }).first().click();
await pg.waitForURL("**/camera");
await pg.getByText(/Câmera indisponível|Sem acesso/).waitFor();
console.log("camera state:", await pg.locator("h1").innerText());
const clicks = 3; // FAB + escolher foto + (resultado automático)
await pg.setInputFiles('input[type=file]', "/tmp/folha.jpg");
await pg.waitForURL("**/diagnostico/**", { timeout: 15000 });
await pg.locator("#res-nome").waitFor();
console.log("resultado:", await pg.locator("#res-nome").innerText(), "|", await pg.getByText(/Muito provável|Provável|Possível/).first().innerText(), "| em", Date.now() - t0, "ms");
await pg.getByRole("button", { name: "Bateu", exact: true }).click();
await pg.getByRole("link", { name: "Ver ficha completa" }).click();
await pg.waitForURL("**/biblioteca/soja/**");
console.log("ficha:", await pg.locator("h2").first().innerText());
// foto escura
await pg.goto(B + "/camera");
await pg.getByText(/Câmera indisponível|Sem acesso/).waitFor();
await pg.setInputFiles('input[type=file]', "/tmp/escura.jpg");
await pg.getByText("A foto ficou escura").waitFor();
console.log("estado foto escura ok");
// offline: fila
await pg.goto(B + "/camera");
await pg.getByText(/Câmera indisponível|Sem acesso/).waitFor();
await ctx.setOffline(true);
await pg.setInputFiles('input[type=file]', "/tmp/folha.jpg");
await pg.getByText("Foto guardada na fila").waitFor();
console.log("fila offline ok");
await ctx.setOffline(false);
await pg.goto(B + "/biblioteca");
await pg.getByText(/Analisando|Pronto|na fila/).first().waitFor({ timeout: 10000 });
await pg.getByText("Pronto! Toque para ver o resultado").waitFor({ timeout: 10000 });
console.log("fila processada ao voltar a rede ok");
console.log("erros de console:", errors.length ? errors : "nenhum");
await b.close();
